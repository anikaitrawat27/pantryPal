import { sql } from "drizzle-orm";
import {
  boolean,
  date,
  index,
  integer,
  jsonb,
  pgTable,
  primaryKey,
  smallint,
  text,
  timestamp,
  uniqueIndex,
} from "drizzle-orm/pg-core";

/**
 * Database schema. Every per-user table cascades on user deletion, so deleting an
 * account removes all of its data.
 */

export const users = pgTable(
  "users",
  {
    id: text("id").primaryKey(),
    /** As typed at signup, for display. */
    username: text("username").notNull(),
    /** Lowercased; uniqueness and lookups use this. */
    usernameKey: text("username_key").notNull(),
    passwordHash: text("password_hash").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [uniqueIndex("users_username_key_idx").on(t.usernameKey)],
);

export const sessions = pgTable(
  "sessions",
  {
    /** SHA-256 of the session token. The token itself is only ever in the cookie. */
    id: text("id").primaryKey(),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("sessions_user_idx").on(t.userId)],
);

export const recoveryCodes = pgTable(
  "recovery_codes",
  {
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    /** SHA-256 of the code. Codes are long random strings, so a fast hash is enough. */
    codeHash: text("code_hash").notNull(),
    usedAt: timestamp("used_at", { withTimezone: true }),
  },
  (t) => [primaryKey({ columns: [t.userId, t.codeHash] })],
);

export const pantryItems = pgTable(
  "pantry_items",
  {
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    ingredientId: text("ingredient_id").notNull(),
    low: boolean("low").notNull().default(false),
  },
  (t) => [primaryKey({ columns: [t.userId, t.ingredientId] })],
);

export const planEntries = pgTable(
  "plan_entries",
  {
    /** Generated by the browser, so it is only unique per user. */
    id: text("id").notNull(),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    day: smallint("day").notNull(),
    meal: text("meal").notNull(),
    slug: text("slug").notNull(),
    servings: smallint("servings").notNull(),
    position: integer("position").notNull().default(0),
  },
  (t) => [primaryKey({ columns: [t.userId, t.id] })],
);

export const favorites = pgTable(
  "favorites",
  {
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    slug: text("slug").notNull(),
    position: integer("position").notNull().default(0),
  },
  (t) => [primaryKey({ columns: [t.userId, t.slug] })],
);

export const shoppingChecks = pgTable(
  "shopping_checks",
  {
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    ingredientId: text("ingredient_id").notNull(),
  },
  (t) => [primaryKey({ columns: [t.userId, t.ingredientId] })],
);

/** Fixed-window counters for login, signup, and reset attempts. */
export const rateLimits = pgTable("rate_limits", {
  key: text("key").primaryKey(),
  windowStart: timestamp("window_start", { withTimezone: true }).notNull(),
  count: integer("count").notNull(),
});

/** Security-relevant account events, for investigating abuse. Never stores secrets. */
export const authEvents = pgTable(
  "auth_events",
  {
    id: integer("id").primaryKey().generatedAlwaysAsIdentity(),
    userId: text("user_id").references(() => users.id, { onDelete: "cascade" }),
    type: text("type").notNull(),
    ip: text("ip"),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .default(sql`now()`),
  },
  (t) => [index("auth_events_user_idx").on(t.userId)],
);

/** A chat thread. The full API transcript is stored server-side so it is replayed exactly and cannot be forged by the client. */
export const chatConversations = pgTable(
  "chat_conversations",
  {
    id: text("id").primaryKey(),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    title: text("title").notNull(),
    lang: text("lang").notNull().default("en"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("chat_conversations_user_idx").on(t.userId, t.updatedAt)],
);

export const chatMessages = pgTable(
  "chat_messages",
  {
    conversationId: text("conversation_id")
      .notNull()
      .references(() => chatConversations.id, { onDelete: "cascade" }),
    seq: integer("seq").notNull(),
    role: text("role").notNull(),
    /** Content blocks exactly as sent to or received from the API, including thinking and tool blocks. */
    content: jsonb("content").notNull(),
    /** For assistant turns: what the page showed (text, recipe cards, generated recipes), for reloading the thread. */
    ui: jsonb("ui"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.conversationId, t.seq] })],
);

/** Recipes the chatbot wrote. Each passed the same validation as the catalog before it was shown. */
export const generatedRecipes = pgTable(
  "generated_recipes",
  {
    id: text("id").primaryKey(),
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    recipe: jsonb("recipe").notNull(),
    saved: boolean("saved").notNull().default(false),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("generated_recipes_user_idx").on(t.userId, t.saved)],
);

/** Daily chat usage per user, for the message limit and cost tracking. */
export const chatUsage = pgTable(
  "chat_usage",
  {
    userId: text("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    day: date("day").notNull(),
    messages: integer("messages").notNull().default(0),
    inputTokens: integer("input_tokens").notNull().default(0),
    outputTokens: integer("output_tokens").notNull().default(0),
    cacheReadTokens: integer("cache_read_tokens").notNull().default(0),
  },
  (t) => [primaryKey({ columns: [t.userId, t.day] })],
);
